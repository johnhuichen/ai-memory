#!/bin/sh
# Generates VARS.md (gitignored) with values for this machine.
set -eu
memory_root="$(cd "$(dirname "$0")" && pwd)"
cat > "$memory_root/VARS.md" <<EOF
# Variables

Values for this machine, generated by \`setup.sh\`. Memory files refer to them by name in angle brackets, for example \`<MEMORY_ROOT>/src/core.md\`. Replace each name with its value below before reading, writing or running anything.

- \`MEMORY_ROOT\`: $memory_root
EOF
echo "Wrote $memory_root/VARS.md"

# Create the memory index if it doesn't exist yet. Never overwrite it: it lists this machine's memories.
index="$memory_root/src/index.md"
if [ ! -e "$index" ]; then
  cat > "$index" <<'EOF'
> This is a memory file governed by `<MEMORY_ROOT>/src/core.md`.

# Memory Index

One entry per memory file in `<MEMORY_ROOT>/src/`, in the format ``- `<MEMORY_ROOT>/src/<file>.md`: <the file's topic in one line>``.

(none yet)
EOF
  echo "Wrote $index"
fi
